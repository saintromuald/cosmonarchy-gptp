#pragma once
#include "core/module.h"
#include "ai/module.h"

namespace lua::api {

inline void generate_lsp_annotations(std::ofstream& out) {
    out << "-- This file contains annotations for Cosmonarchy's Lua API, which can be used by LSP servers to provide autocompletion and type checking.\n";
    out << "-- Cosmonarchy automatically generates this file when the game is run, do not edit this file manually!\n\n";
    core::Module::lsp_annotations(out);
    ai::Module::lsp_annotations(out);
}

inline void install(ScriptManager& manager, sol::state& lua) {
    core::Module::install(manager, lua);
    ai::Module::install(manager, lua);
}

} // namespace lua::api
